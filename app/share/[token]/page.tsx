import Link from "next/link";
import { format, eachDayOfInterval, startOfMonth, endOfMonth, startOfWeek, endOfWeek } from "date-fns";
import { prisma } from "@/lib/prisma";
import { serializePost } from "@/lib/serializers";
export default async function SharePage({
  params,
}: {
  params: { token: string };
}) {
  const share = await prisma.shareToken.findUnique({
    where: { token: params.token },
    include: { brand: true },
  });

  if (!share || share.expiresAt < new Date()) {
    return (
      <div className="flex min-h-screen items-center justify-center bg-[var(--bg-base)] p-6 text-center">
        <div>
          <h1 className="font-heading text-2xl font-bold">Link expired or invalid</h1>
          <Link href="/" className="mt-4 inline-block text-[var(--accent-brand)]">
            View in Calendo →
          </Link>
        </div>
      </div>
    );
  }

  const start = new Date(share.year, share.month - 1, 1);
  const end = new Date(share.year, share.month, 0, 23, 59, 59, 999);

  const posts = await prisma.post.findMany({
    where: {
      brandId: share.brandId,
      scheduledAt: { gte: start, lte: end },
    },
    orderBy: { scheduledAt: "asc" },
  });

  const serialized = posts.map(serializePost);
  const monthDate = new Date(share.year, share.month - 1, 1);
  const days = eachDayOfInterval({
    start: startOfWeek(startOfMonth(monthDate)),
    end: endOfWeek(endOfMonth(monthDate)),
  });

  const byDay = new Map<string, typeof serialized>();
  for (const p of serialized) {
    const key = format(new Date(p.scheduledAt), "yyyy-MM-dd");
    const list = byDay.get(key) ?? [];
    list.push(p);
    byDay.set(key, list);
  }

  return (
    <div className="min-h-screen bg-[var(--bg-base)] p-6">
      <header className="mb-8 text-center">
        <h1 className="font-heading text-3xl font-bold">{share.brand.name}</h1>
        <p className="text-[var(--text-secondary)]">
          {format(monthDate, "MMMM yyyy")} — Designer view (read-only)
        </p>
        <Link
          href="/"
          className="mt-4 inline-block rounded-lg bg-[var(--accent-brand)] px-4 py-2 text-sm text-white"
        >
          View in Calendo
        </Link>
      </header>
      <div className="mx-auto max-w-6xl">
        <div className="grid grid-cols-7 gap-0">
          {["Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"].map((d) => (
            <div key={d} className="border border-[var(--cal-border)] py-2 text-center text-xs text-[var(--text-secondary)]">
              {d}
            </div>
          ))}
          {days.map((date) => {
            const dayPosts = byDay.get(format(date, "yyyy-MM-dd")) ?? [];
            return (
              <div
                key={date.toISOString()}
                className="min-h-[80px] border border-[var(--cal-border)] bg-[var(--bg-surface)] p-1"
              >
                <span className="text-xs text-[var(--text-secondary)]">{format(date, "d")}</span>
                {dayPosts.map((p) => (
                  <details key={p.id} className="mt-1 rounded bg-[var(--bg-elevated)] p-1 text-[10px]">
                    <summary className="cursor-pointer font-medium">{p.title}</summary>
                    <p className="mt-1 text-[var(--text-secondary)]">{p.caption}</p>
                    <p className="text-[var(--text-secondary)]">{p.hashtags.join(" ")}</p>
                    <p className="italic">{p.designerNote}</p>
                    <p>{p.platforms.join(", ")} · {p.postType}</p>
                  </details>
                ))}
              </div>
            );
          })}
        </div>
      </div>
      <footer className="mt-8 text-center text-xs text-[var(--text-secondary)]">
        Generated by Calendo
      </footer>
    </div>
  );
}
